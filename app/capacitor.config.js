// Plain JS rather than .ts on purpose: this folder ships a prebuilt static
// payload and has no TypeScript source, and @capacitor/cli requires a full
// typescript install just to read a .ts config.

// Capacitor 8 loads a JavaScript config through `require()`, so this deliberately
// uses CommonJS. An ESM default export is wrapped as `{ default: ... }` and makes
// `cap add` think appId is missing.

// One id for iOS and Android, as Hexsweeper does. Reverse of the game's own
// domain, playnotan.com. PROPOSED, not yet confirmed by the owner: an App Store
// bundle id and a Google Play application id are permanent after the first
// upload. See README.md, "Decisions for the owner".
const appId = "com.playnotan.app";
const appName = "Notan";
// Generated by scripts/export-www.py from the game at the repository root; see WWW_SOURCE.txt.
const webDir = "www";
const loggingBehavior = "production";

/** @type {import('@capacitor/cli').CapacitorConfig} */
const config = {
  appId,
  appName,
  webDir,
  loggingBehavior,
  ios: {
    // The game pads itself with env(safe-area-inset-*) under viewport-fit=cover.
    contentInset: "never",
    // Nothing on the board scrolls the page; sheets scroll inside themselves.
    scrollEnabled: false,
  },
  android: {
    // The payload never loads anything over http.
    allowMixedContent: false,
  },
};

module.exports = config;
